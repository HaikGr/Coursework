import unittest

from dbmanager.sql import generator as sqlgen
from dbmanager.sql.identifiers import quote_identifier


class QuoteIdentifierTest(unittest.TestCase):
    def test_bare_when_the_database_reads_the_name_back_unchanged(self):
        self.assertEqual(quote_identifier("customers", "POSTGRESQL"), "customers")
        self.assertEqual(quote_identifier("CUSTOMERS", "H2"), "CUSTOMERS")
        self.assertEqual(quote_identifier("Customers", "MYSQL"), "Customers")

    def test_quoted_for_mixed_case_reserved_words_and_odd_characters(self):
        self.assertEqual(quote_identifier("Customers", "POSTGRESQL"), '"Customers"')
        self.assertEqual(quote_identifier("order", "POSTGRESQL"), '"order"')
        self.assertEqual(quote_identifier("my table", "MYSQL"), "`my table`")
        self.assertEqual(quote_identifier("a]b", "SQLSERVER"), "[a]]b]")
        self.assertEqual(quote_identifier('say "hi"', "POSTGRESQL"), '"say ""hi"""')


class LiteralTest(unittest.TestCase):
    def test_numbers_booleans_and_null(self):
        self.assertEqual(sqlgen.literal("42", "int4", "POSTGRESQL"), "42")
        self.assertEqual(sqlgen.literal("$1,5", "money", "POSTGRESQL"), "'$1,5'")
        self.assertEqual(sqlgen.literal("$15.50", "money", "SQLSERVER"), "15.50")
        self.assertEqual(sqlgen.literal("yes", "bool", "POSTGRESQL"), "TRUE")
        self.assertEqual(sqlgen.literal("true", "bit", "SQLSERVER"), "1")
        self.assertEqual(sqlgen.literal(None, "text", "POSTGRESQL"), "NULL")
        self.assertEqual(sqlgen.literal(" null ", "text", "POSTGRESQL"), "NULL")
        self.assertEqual(sqlgen.literal("", "int", "POSTGRESQL"), "NULL")

    def test_text_is_escaped_per_dialect(self):
        self.assertEqual(sqlgen.literal("it's", "text", "POSTGRESQL"), "'it''s'")
        self.assertEqual(sqlgen.literal("C:\\x", "varchar", "MYSQL"), "'C:\\\\x'")
        self.assertEqual(sqlgen.literal("ok", "nvarchar", "SQLSERVER"), "N'ok'")
        self.assertEqual(sqlgen.literal("", "varchar", "POSTGRESQL"), "''")


class StatementTest(unittest.TestCase):
    def test_create_table_with_identity_and_foreign_key(self):
        columns = [["id", "int", "Not Null", "PK", "-", "-", "AUTO"], ["customer_id", "int", "Null", "FK", "-", "-", "-"]]
        sql = sqlgen.create_table("orders", columns, [("customer_id", "customers", "id")], "POSTGRESQL")
        self.assertEqual(sql, "CREATE TABLE orders (\n"
                              "    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n"
                              "    customer_id integer,\n"
                              "    PRIMARY KEY (id),\n"
                              "    FOREIGN KEY (customer_id) REFERENCES customers (id)\n)")
        self.assertIn("id INT AUTO_INCREMENT NOT NULL", sqlgen.create_table("orders", columns, [], "MYSQL"))
        self.assertIn("id INT IDENTITY(1,1) NOT NULL", sqlgen.create_table("orders", columns, [], "SQLSERVER"))

    def test_sql_server_rename_quotes_the_old_name_as_an_object_path(self):
        self.assertEqual(sqlgen.rename_column("my table", "old", "new", "SQLSERVER"),
                         "EXEC sp_rename N'[my table].old', N'new', N'COLUMN'")
        self.assertEqual(sqlgen.rename_column("t", "a'b", "c", "SQLSERVER"),
                         "EXEC sp_rename N't.[a''b]', N'c', N'COLUMN'")
        self.assertEqual(sqlgen.rename_column("t", "a", "B", "POSTGRESQL"), 'ALTER TABLE t RENAME COLUMN a TO "B"')

    def test_drop_view(self):
        self.assertEqual(sqlgen.drop_table("v", "POSTGRESQL", view=True), "DROP VIEW v")
        self.assertEqual(sqlgen.drop_table("t", "POSTGRESQL"), "DROP TABLE t")

    def test_insert_update_delete(self):
        self.assertEqual(sqlgen.insert("t", [], "POSTGRESQL"), "INSERT INTO t DEFAULT VALUES")
        self.assertEqual(sqlgen.insert("t", [], "MYSQL"), "INSERT INTO t () VALUES ()")
        self.assertEqual(sqlgen.update("t", [("name", "'x'")], [("id", "1"), ("note", "NULL")], "POSTGRESQL"),
                         "UPDATE t SET name = 'x' WHERE id = 1 AND note IS NULL")
        self.assertEqual(sqlgen.delete("t", [("id", "1")], "POSTGRESQL"), "DELETE FROM t WHERE id = 1")

    def test_type_helpers(self):
        self.assertTrue(sqlgen.is_integer_type("int4"))
        self.assertTrue(sqlgen.is_integer_type("INT UNSIGNED"))
        self.assertFalse(sqlgen.is_integer_type("interval"))
        self.assertFalse(sqlgen.is_integer_type("point"))
        self.assertTrue(sqlgen.is_exact_decimal_type("numeric(10,2)"))
        self.assertTrue(sqlgen.is_money_type("smallmoney"))
        self.assertFalse(sqlgen.is_money_type("decimal"))


if __name__ == "__main__":
    unittest.main()
